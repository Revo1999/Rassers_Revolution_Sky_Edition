    write(ROOT/'pack/overrides/config/ftbquests/quests/chapters/5e60000000000000.snbt',{'id':'5E60000000000000','filename':'5e60000000000000','title':'Wither Containment','icon':{'id':'revoindustry:wither_egg','count':1},'order_index':50,'default_quest_shape':'circle','quests':quests})

