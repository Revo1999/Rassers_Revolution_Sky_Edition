"""Paint native pixel clusters and generate data for the Blockbench-authored Wither chamber.

Geometry is authored/exported through Blockbench MCP, not generated by this script.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import json
import io
import zipfile

ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'art/blockbench/wither-hatchery'
RES=ROOT/'revoindustry/src/main/resources'
TEX=RES/'assets/revoindustry/textures/block'

def write(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,indent=2)+'\n',encoding='utf-8')

def paint():
    ART.mkdir(parents=True,exist_ok=True);TEX.mkdir(parents=True,exist_ok=True)
    im=Image.new('RGBA',(128,128),(0,0,0,0));d=ImageDraw.Draw(im)
    # Atlas tiles: steel, vent, input, output, energy, controller, lamp off/on, glass, egg.
    for tile in range(8):
        x=tile*16
        d.rectangle((x,0,x+15,15),fill='#333b46');d.rectangle((x+1,1,x+14,14),fill='#4b5663')
        d.line((x+1,1,x+14,1),fill='#79838b');d.line((x+14,2,x+14,14),fill='#252c35')
        # Deliberate two-pixel material clusters, no photographic grain.
        for a,b in [(3,4),(9,3),(5,10),(11,11)]:
            d.line((x+a,b,x+a+1,b),fill='#596572');d.point((x+a,b+1),fill='#434e5b')
        for a,b in [(2,2),(13,2),(2,13),(13,13)]:d.point((x+a,b),fill='#9aa0a0')
    for y in [5,8,11]:d.rectangle((19,y,28,y+1),fill='#1d252d')
    for tile,color,direction in [(2,'#c7a65a',1),(3,'#88b69c',-1)]:
        x=tile*16;d.rectangle((x+3,3,x+12,12),fill='#1d2630')
        d.line((x+5,7,x+10,7),fill=color,width=2)
        end=x+10 if direction==1 else x+5
        d.line((end-direction*2,5,end,7),fill=color);d.line((end-direction*2,9,end,7),fill=color)
    d.rectangle((68,3,75,12),fill='#191e28');d.line((72,4,69,8,73,8,70,12),fill='#d28665',width=2)
    d.rectangle((83,3,92,11),fill='#101c21');d.rectangle((84,4,91,5),fill='#9fc7bd');d.rectangle((84,7,88,8),fill='#b55450');d.line((85,13,90,13),fill='#0b0c10')
    for tile,on in [(6,False),(7,True)]:
        x=tile*16;d.rectangle((x+4,2,x+11,13),fill='#1a1e27');d.rectangle((x+5,3,x+10,12),fill='#fa5149' if on else '#752b35')
        for y in [4,7,10]:d.line((x+6,y,x+9,y),fill='#ffc1a1' if on else '#a04848')
    # Use the exact native MI steel and the existing furnace hatch overlay recipe.
    with zipfile.ZipFile(ROOT/'.local/integration-mods/Modern-Industrialization-2.5.11.jar') as mi:
        def sprite(path):return Image.open(io.BytesIO(mi.read('assets/modern_industrialization/textures/block/'+path+'.png'))).convert('RGBA').crop((0,0,16,16))
        steel=sprite('steel_machine_casing')
        for tile in range(8):im.paste(steel,(tile*16,0))
        for tile,overlay in [(2,'output'),(3,'output_item'),(4,'output_energy')]:
            face=steel.copy();face.alpha_composite(sprite('overlays/'+overlay));face.alpha_composite(sprite('overlays/item_auto'));im.paste(face,(tile*16,0))
        d=ImageDraw.Draw(im)
        d.rectangle((83,3,92,11),fill='#101c21');d.rectangle((84,4,91,5),fill='#9fc7bd');d.rectangle((84,7,88,8),fill='#b55450');d.line((85,13,90,13),fill='#0b0c10')
        for tile,on in [(6,False),(7,True)]:
            x=tile*16;d.rectangle((x+3,1,x+12,14),fill='#14151b')
            for yy in range(2,14):
                for xx in range(4,12):
                    edge=min(xx-4,11-xx,yy-2,13-yy)
                    palette=['#a42d3b','#db4248','#ef6554'] if on else ['#49212d','#702e3a','#98454a']
                    index=min(2,edge)+(1 if (xx+yy)%2==0 and edge==0 else 0)
                    color=palette[min(2,index)]
                    if on and edge>=2 and (xx+yy)%2==0:color='#ff9d76'
                    d.point((x+xx,yy),fill=color)
    # Smoky glass: translucent dark blue-grey with small pixel highlights.
    d.rectangle((0,16,15,31),fill=(25,32,43,92))
    d.line((2,19,4,17),fill=(133,157,167,110));d.line((10,29,13,26),fill=(101,129,143,95))
    for stage in range(3):
        x=16+stage*16;d.rectangle((x,16,x+15,31),fill='#26232f')
        for a,b in [(2,3),(8,2),(11,8),(4,10),(7,13)]:
            d.rectangle((x+a,16+b,x+a+1,17+b),fill='#3d354b');d.point((x+a,18+b),fill='#302c3b')
        if stage:
            d.line((x+8,16,x+7,20,x+10,22,x+6,25,x+8,31),fill='#d34b52' if stage==1 else '#ff8b78')
            if stage==2:d.line((x+6,25,x+2,24,x,26),fill='#ff8b78');d.line((x+10,22,x+14,21,x+15,22),fill='#e15a62')
    im.save(TEX/'wither_chamber_atlas.png');im.save(ART/'wither_chamber_atlas.png')
    (ART/'CREDITS.txt').write_text('Steel casing and item/energy hatch sprites: Modern Industrialization 2.5.11, AztechMC / MI contributors.\nSource: pinned Modern-Industrialization-2.5.11.jar.\nHatch compositing matches the existing RevoIndustry furnace multiblocks at original native pixel positions.\nGlass, egg, controller and dithered red lamps: Revo project artwork. Geometry authored through Blockbench MCP.\n',encoding='utf-8')
    for name,box in [('glass',(0,16,16,32)),('light_off',(96,0,112,16)),('light_on',(112,0,128,16))]:im.crop(box).save(TEX/f'wither_chamber_{name}.png')

def data():
    names={'wither_chamber_casing':'Wither Containment Casing','wither_chamber_glass':'Smoked Containment Glass','wither_chamber_light':'Red Hatching Light','wither_hatchery':'Electric Wither Hatchery','wither_egg_input_hatch':'Wither Egg Input Hatch','wither_star_output_hatch':'Nether Star Output Hatch','wither_energy_hatch':'Wither Chamber Energy Hatch'}
    langpath=RES/'assets/revoindustry/lang/en_us.json';lang=json.loads(langpath.read_text(encoding='utf-8-sig'))
