    shaped('wither_chamber_light',['GRG','RCR','GRG'],{'G':'minecraft:glass','R':'minecraft:redstone','C':'revoindustry:wither_chamber_casing'},4)
    shaped('wither_egg_input_hatch',[' S ','HCH',' S '],{'S':'modern_industrialization:steel_plate','H':'minecraft:hopper','C':'revoindustry:wither_chamber_casing'})
    shaped('wither_star_output_hatch',[' H ','SCS',' H '],{'S':'modern_industrialization:steel_plate','H':'minecraft:hopper','C':'revoindustry:wither_chamber_casing'})
    shaped('wither_energy_hatch',['WTW','TCT','WTW'],{'W':'modern_industrialization:tin_cable','T':'modern_industrialization:analog_circuit','C':'revoindustry:wither_chamber_casing'})
    shaped('wither_hatchery',['OAO','DCD','OMO'],{'O':'minecraft:obsidian','A':'modern_industrialization:analog_circuit','D':'minecraft:diamond','C':'revoindustry:wither_chamber_casing','M':'modern_industrialization:motor'})
    tagpath=RES/'data/minecraft/tags/block/mineable/pickaxe.json'
